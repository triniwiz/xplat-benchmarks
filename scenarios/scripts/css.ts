const lineHeight = (size: number) => Math.round(size * 1.4);

/** Color utility classes (bg-i, bgl-i, bc-i). Colors only, so valid for NS core and Mason CSS too. */
export function paletteClasses(): string {
  const out: string[] = [];
  palette.forEach((c, i) => {
    out.push(`.bg-${i} { background-color: ${c}; }`);
    out.push(`.bgl-${i} { background-color: ${paletteLight[i]}; }`);
    out.push(`.bc-${i} { border-color: ${c}; }`);
  });
  return out.join('\n');
}

function fontClasses(): string {
  return fontSizes
    .map((s, i) => `.fs-${i} { font-size: ${s}px; line-height: ${lineHeight(s)}px; }`)
    .join('\n');
}

